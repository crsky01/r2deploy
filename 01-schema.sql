-- PostgREST 连接角色（内部使用）
-- 注意：psql 变量 + \gexec 方式，避免 DO 块中 CREATE ROLE 不生效的问题
SELECT 'CREATE ROLE authenticator NOINHERIT LOGIN PASSWORD ' || quote_literal(:'auth_password') || ';'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticator')\gexec

SELECT 'ALTER ROLE authenticator WITH LOGIN PASSWORD ' || quote_literal(:'auth_password') || ';'
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticator')\gexec

-- 1. 业务员/客服表
CREATE TABLE IF NOT EXISTS agents (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  whatsapps TEXT[] DEFAULT '{}',
  password TEXT NOT NULL,
  active BOOLEAN DEFAULT true,
  assigned_count INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. 贷款申请表
CREATE TABLE IF NOT EXISTS applications (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  whatsapp TEXT NOT NULL,
  cpf TEXT DEFAULT '',
  iphone_model TEXT NOT NULL,
  imei TEXT NOT NULL,
  amount INTEGER NOT NULL DEFAULT 0,
  country TEXT DEFAULT 'BR',
  status TEXT DEFAULT 'pending',
  assigned_agent TEXT,
  agent_whatsapp TEXT,
  source TEXT,
  doc_front TEXT,
  doc_back TEXT,
  user_id TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  approved_at TIMESTAMPTZ,
  loan_term_months INTEGER DEFAULT 0,
  monthly_payment INTEGER DEFAULT 0,
  due_date TIMESTAMPTZ,
  disbursed_amount INTEGER DEFAULT 0,
  disbursed_at TIMESTAMPTZ
);

-- 3. 用户表
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  phone TEXT NOT NULL,
  password TEXT NOT NULL,
  referral_code TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. 推荐记录表
CREATE TABLE IF NOT EXISTS referrals (
  id TEXT PRIMARY KEY,
  referrer_id TEXT NOT NULL,
  referred_user_id TEXT NOT NULL,
  referred_name TEXT NOT NULL,
  referral_code TEXT NOT NULL,
  reward_percent INTEGER DEFAULT 30,
  reward_amount INTEGER DEFAULT 0,
  reward_status TEXT DEFAULT 'pending',
  application_id TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. Token 表（用户/管理员登录 token）
CREATE TABLE IF NOT EXISTS tokens (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 6. 管理员 token 表
CREATE TABLE IF NOT EXISTS admin_tokens (
  token TEXT PRIMARY KEY,
  expires_at BIGINT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 6.1 管理员子账号表（多管理员登录）
CREATE TABLE IF NOT EXISTS admin_accounts (
  id TEXT PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  totp_secret TEXT NOT NULL,
  totp_bound BOOLEAN DEFAULT false,
  active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 7. 站点统计表（访问量 / WS 点击 / 渠道追踪）
CREATE TABLE IF NOT EXISTS site_stats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  value TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT now()
);

-- =============================================
-- 索引（避免全表扫描）
-- =============================================
CREATE INDEX IF NOT EXISTS idx_applications_status ON applications(status);
CREATE INDEX IF NOT EXISTS idx_applications_user_id ON applications(user_id);
CREATE INDEX IF NOT EXISTS idx_applications_assigned_agent ON applications(assigned_agent);
CREATE INDEX IF NOT EXISTS idx_applications_created ON applications(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_agents_name ON agents(name);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_referral_code ON users(referral_code);
CREATE INDEX IF NOT EXISTS idx_tokens_expires ON tokens(expires_at);
CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON referrals(referrer_id);
CREATE INDEX IF NOT EXISTS idx_site_stats_type_created ON site_stats(type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_site_stats_value ON site_stats(type, value, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_admin_accounts_username ON admin_accounts(username);

-- =============================================
-- 权限：authenticator 角色（PostgREST 用它访问）
-- =============================================
GRANT USAGE ON SCHEMA public TO authenticator;
GRANT ALL ON ALL TABLES IN SCHEMA public TO authenticator;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO authenticator;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO authenticator;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO authenticator;

